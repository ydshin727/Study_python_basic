"""
07. NumPy: 숫자 배열을 빠르게 계산하기

AI에서 데이터는 전부 숫자 배열입니다. 센서 측정값도, 분자 지문도, 신경망도 마찬가지입니다.
NumPy를 이해하면 PyTorch의 텐서도 거의 그대로 이해할 수 있습니다.

핵심 세 가지: shape(모양), axis(방향), 브로드캐스팅(자동 크기 맞춤)

실행: python lessons/07_numpy.py
"""

import numpy as np  # np라는 줄임말로 쓰는 것이 관례입니다.

# ---------------------------------------------------------------------
# 1. 배열 만들기, 리스트와의 차이
# ---------------------------------------------------------------------
python_list = [1.0, 1.2, 1.5]
array = np.array(python_list)

print(python_list * 2)  # 리스트 × 2 → 이어 붙이기
print(array * 2)  # 배열 × 2 → 값마다 계산!

# for문 없이 한 번에 계산하는 것을 '벡터화'라고 하며, 훨씬 빠릅니다.
print(array - 1.0)
print(array > 1.1)  # 비교도 값마다 계산됩니다.

print(np.zeros(3), np.ones(2), np.arange(5))
print(np.linspace(0, 1, 5))  # 0부터 1까지 5등분

# ---------------------------------------------------------------------
# 2. shape: 2차원 배열은 표입니다
#    행(가로줄) = 측정 시점, 열(세로줄) = 센서
# ---------------------------------------------------------------------
readings = np.array(
    [
        # s1   s2   s3   s4
        [1.0, 1.1, 0.9, 1.0],  # 0초
        [1.8, 1.2, 1.5, 1.1],  # 1초
        [2.2, 1.3, 1.9, 1.2],  # 2초
        [1.6, 1.2, 1.4, 1.1],  # 3초
    ]
)
print(readings.shape)  # (4, 4) → (행, 열)
print(readings.ndim, readings.size, readings.dtype)

# 💡 딥러닝 오류의 절반 이상은 shape 불일치입니다.
#    막히면 일단 print(x.shape)부터 해 보세요.

print(readings.reshape(2, 8).shape)  # 값의 총개수가 같으면 모양을 바꿀 수 있습니다.
print(readings.flatten().shape)  # 1차원으로 펼치기

# ---------------------------------------------------------------------
# 3. 인덱싱: 원하는 부분 꺼내기. [행, 열] 순서입니다.
# ---------------------------------------------------------------------
print(readings[1, 0])  # 1행 0열 하나
print(readings[1])  # 1행 전체 → 1초일 때 모든 센서
print(readings[:, 0])  # 모든 행의 0열 → s1 센서의 시계열
print(readings[1:3, :2])  # 1~2행, 0~1열

# 조건으로 고르기(불리언 인덱싱): 아주 자주 씁니다.
s1 = readings[:, 0]
print(s1[s1 > 1.5])  # 1.5보다 큰 값만
print(np.where(s1 > 1.5)[0])  # 조건을 만족하는 위치

# ---------------------------------------------------------------------
# 4. axis: 어느 방향으로 계산할까
#    axis=0 → 행을 따라 세로로 합칩니다 (결과: 센서별 값)
#    axis=1 → 열을 따라 가로로 합칩니다 (결과: 시점별 값)
#    '없어지는 방향'이라고 기억하면 쉽습니다.
# ---------------------------------------------------------------------
print(readings.mean())  # 전체 평균 → 값 하나
print(readings.mean(axis=0))  # 센서별 평균 → 길이 4
print(readings.max(axis=1))  # 시점별 최댓값 → 길이 4
print(readings.argmax(axis=0))  # 센서마다 최고점이 나온 위치

# ---------------------------------------------------------------------
# 5. 브로드캐스팅: 크기가 달라도 알아서 맞춰 계산
# ---------------------------------------------------------------------
baseline = readings[0]  # 0초(냄새 없음)의 값을 기준으로 삼습니다. shape (4,)
corrected = readings - baseline  # (4, 4) - (4,) → 모든 행에서 baseline을 뺍니다.
print(corrected.round(2))

peak = corrected.max(axis=0)  # 센서별 최대 반응
print(peak.round(2))

# ---------------------------------------------------------------------
# 6. 정규화: 농도가 달라도 패턴을 비교하기
# ---------------------------------------------------------------------
weak = np.array([0.5, 0.1, 0.3, 0.1])
strong = weak * 3  # 같은 냄새를 세 배 진하게 맡은 경우
other = np.array([0.1, 0.5, 0.1, 0.3])  # 다른 냄새


def unit_vector(vector):
    return vector / np.linalg.norm(vector)  # norm: 벡터의 길이


print(np.allclose(unit_vector(weak), unit_vector(strong)))  # True: 패턴이 같습니다.

# 코사인 유사도: 04번에서 for로 썼던 코드가 한 줄이 됩니다.
print(unit_vector(weak) @ unit_vector(strong))  # '@'는 내적(dot product)입니다.
print(unit_vector(weak) @ unit_vector(other))

# ---------------------------------------------------------------------
# 7. 난수: 씨앗값을 고정하면 결과를 재현할 수 있습니다.
# ---------------------------------------------------------------------
rng = np.random.default_rng(42)
noise = rng.normal(0, 0.02, size=(4, 4))  # 평균 0, 표준편차 0.02
print((readings + noise).round(2))

